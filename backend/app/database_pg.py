_engines: dict[str, Engine] = {}
_lock = threading.Lock()


def environment_flag(name: str) -> bool:
    """Converte uma variável de ambiente comum em uma opção booleana."""
    return os.getenv(name, '').strip().lower() in {'1', 'true', 'yes', 'on'}


def postgres_schema():
    """Retorna o schema configurado e bloqueia nomes que poderiam alterar o SQL."""
    schema = os.getenv('POSTGRES_SCHEMA', 'public').strip() or 'public'
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', schema):
        raise RuntimeError('POSTGRES_SCHEMA deve ser um identificador PostgreSQL válido.')
    return schema


def database_url() -> URL:
    """Monta a URL do SQLAlchemy a partir de DATABASE_URL ou das variáveis POSTGRES_*."""
    raw_url = os.getenv('DATABASE_URL', '').strip()
    if raw_url:
        settings = conninfo_to_dict(raw_url)
        host_override = os.getenv('POSTGRES_HOST', '').strip()
        if host_override:
            settings['host'] = host_override
    else:
        settings = {
            'host': os.getenv('POSTGRES_HOST', 'localhost'),
            'port': os.getenv('POSTGRES_PORT', '5432'),
            'dbname': os.getenv('POSTGRES_DB', 'api5_relacional'),
            'user': os.getenv('POSTGRES_USER', ''),
            'password': os.getenv('POSTGRES_PASSWORD', ''),
        }
        if not settings['user'] or not settings['password']:
            raise RuntimeError('Configure DATABASE_URL ou POSTGRES_USER e POSTGRES_PASSWORD.')
    port = settings.pop('port', None)
    return URL.create(
        DRIVER,
        username=settings.pop('user', None) or None,
        password=settings.pop('password', None) or None,
        host=settings.pop('host', None) or None,
        port=int(port) if port else None,
        database=settings.pop('dbname', None) or None,
        query={key: str(value) for key, value in settings.items()},  # sslmode etc.
    )


def get_engine() -> Engine:
    """Um engine (com pool de conexões) por URL, criado sob demanda."""
    url = database_url()
    key = url.render_as_string(hide_password=False)
    with _lock:
        engine = _engines.get(key)
        if engine is None:
            engine = create_engine(url, pool_pre_ping=True)
            _engines[key] = engine
        return engine


def _quoted(schema: str) -> str:
    # O nome já foi validado por postgres_schema(), então aspas duplas bastam.
    return '"' + schema + '"'


def initialize_schema(session, schema):
    """Cria schema, tabelas base e aplica as migrações, dentro da transação da sessão."""
    from app.core.migrations import apply_migrations

    connection = session.connection()
    connection.exec_driver_sql(f'CREATE SCHEMA IF NOT EXISTS {_quoted(schema)}')
    connection.exec_driver_sql(f'SET LOCAL search_path TO {_quoted(schema)}')
    for statement in BASE_DDL:
        connection.exec_driver_sql(statement)
    apply_migrations(session)


@contextmanager
def database():
    """Entrega uma Session: confirma no sucesso e desfaz tudo quando ocorre um erro."""
    session = Session(get_engine(), expire_on_commit=False)
    try:
        initialize_schema(session, postgres_schema())
        yield session
        session.commit()
    except Exception:
        session.rollback()
        raise
    finally:
        session.close()


def now():
    """Gera datas em UTC no mesmo formato usado nos registros e nas respostas."""
    return datetime.now(timezone.utc).isoformat()


def to_datetime(value):
    """Converte o texto ISO (usado nos JSON das solicitações) em datetime para colunas TIMESTAMPTZ."""
    if value is None or isinstance(value, datetime):
        return value
    text_value = str(value).strip()
    if text_value.endswith('Z'):
        text_value = text_value[:-1] + '+00:00'
    parsed = datetime.fromisoformat(text_value)
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def json_data(value):
    """Normaliza o JSONB, que pode chegar do driver como dicionário ou texto."""
    return value if isinstance(value, dict) else json.loads(value)