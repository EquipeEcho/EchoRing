-- Applied transactionally by initialize_schema; amounts are BRL, never client prices.
ALTER TABLE services ADD COLUMN IF NOT EXISTS translator_compensation NUMERIC(12,2)
    CHECK (translator_compensation > 0);
CREATE TABLE IF NOT EXISTS job_offers (
    id TEXT PRIMARY KEY,
    request_id TEXT NOT NULL REFERENCES requests(id),
    translator_id TEXT NOT NULL REFERENCES users(id),
    created_by TEXT NOT NULL REFERENCES users(id),
    compensation NUMERIC(12,2) NOT NULL CHECK (compensation > 0),
    deadline DATE NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    description TEXT NOT NULL,
    requirements TEXT NOT NULL DEFAULT '',
    volume TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'declined', 'expired', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMPTZ,
    service_id TEXT REFERENCES services(id),
    CHECK (expires_at > created_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS job_offers_pending_recipient
    ON job_offers(request_id, translator_id) WHERE status = 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS job_offers_one_acceptance
    ON job_offers(request_id) WHERE status = 'accepted';
CREATE INDEX IF NOT EXISTS job_offers_inbox ON job_offers(translator_id, created_at DESC);
CREATE INDEX IF NOT EXISTS job_offers_expiration ON job_offers(expires_at) WHERE status = 'pending';
CREATE TABLE IF NOT EXISTS job_offer_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id TEXT NOT NULL REFERENCES job_offers(id),
    status TEXT NOT NULL,
    actor_id TEXT REFERENCES users(id),
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS job_offer_events_offer ON job_offer_events(offer_id, id);
CREATE TABLE IF NOT EXISTS offer_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id),
    offer_id TEXT NOT NULL REFERENCES job_offers(id),
    message TEXT NOT NULL,
    href TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS offer_notifications_user ON offer_notifications(user_id, id DESC);
